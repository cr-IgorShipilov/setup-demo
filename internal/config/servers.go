// Package config implements a hand-rolled reader/writer for the fixed
// servers.yml schema used by this demo. A full YAML library is
// intentionally avoided for v1 (see architecture notes); the schema is
// small and fixed, so a minimal line-based parser is sufficient and keeps
// the binary dependency-free.
package config

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

// Server represents one target host's network configuration, matching the
// fixed servers.yml schema: fqdn, ip, netmask, gw, dns1, dns2.
type Server struct {
	FQDN    string
	IP      string
	Netmask string
	Gateway string
	DNS1    string
	DNS2    string
}

